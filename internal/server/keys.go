// Keys from the control store (design §15.2, decision 22). The daemon
// writes every key of an active principal to a file in authorized_keys
// form (Config.KeysFile), and sshd reads it with AuthorizedKeysFile,
// before the authorized_keys file the operator maintains by hand
// (decision 26), so a key in both comes in by the line that names its
// fingerprint. sshd asks the daemon nothing, so nothing reaches the
// daemon before sshd has authenticated a key.
//
// The file is a cache, and the store decides: each line's forced command
// names its key's fingerprint, and the handshake refuses a bridge that
// names a key the store does not hold for that principal (keyHolds). A
// key that was removed and is still in a file the daemon could not
// rewrite gets past sshd and no further.

const (
	// DefaultKeysFile is where the keys file is written, under the home
	// directory of the user starfixd runs as (Settings.KeyFiles).
	DefaultKeysFile = ".ssh/starfix_keys"
	// DefaultAuthorizedKeys is where the hand-maintained file is read,
	// under the same directory.
	DefaultAuthorizedKeys = ".ssh/authorized_keys"
	// DefaultBridge is the path of starfixd in the forced command of each
	// line of the keys file, as docs/server.md installs it.
	DefaultBridge = "/usr/local/bin/starfixd"

	// keysFileHeader is the first line of the keys file. A file that
	// exists and does not start with it is not the daemon's, and is
	// never overwritten.
	keysFileHeader = "# Generated by starfixd from its control database. Do not edit: changes are overwritten. Manage keys with `sfx admin key`.\n"

	// maxAuthorizedKeys bounds what is read of the hand-maintained
	// authorized_keys file, to say which of the store's keys it also
	// holds. Lines past it are not seen.
	maxAuthorizedKeys = 1 << 20
)

// bridgePattern is what the path of the starfixd binary in a forced
// command may look like: absolute, with nothing that needs quoting in an
// authorized_keys option or in the shell sshd runs the command with.
var bridgePattern = lazyregexp.New(`^(/[A-Za-z0-9._+-]+)+$`)

// ValidBridge reports whether path may be the starfixd binary named in a
// forced command (Config.Bridge): absolute, of letters, digits and ._+-.
func ValidBridge(path string) bool { return bridgePattern.MatchString(path) }

// keysFile is what the server knows of the keys file it writes.
type keysFile struct {
	// mu serializes writes of the file, and guards the rest.
	mu sync.Mutex
	// keys is how many keys the latest write put in the file, at the
	// time the file took that content; failed says the latest attempt
	// did not succeed.
	keys   int
	at     time.Time
	failed bool
	// held is how many of the store's keys the latest rendering left
	// out because the hand-maintained file gives them to another
	// principal.
	held int
	// hand caches the fingerprints in the hand-maintained file, as of
	// the file's size and time, and handOwner the principal each line's
	// forced command names, for the lines that name one.
	hand      map[string]bool
	handOwner map[string]string
	handSize  int64
	handTime  time.Time
}

// WriteKeys writes the keys file from the control store's memory, unless
// the file already holds exactly that: a first line that says starfixd
// generates the file, then one line for each key of an active principal,
//
//	restrict,command="BRIDGE stdio --principal NAME --key FINGERPRINT" TYPE BASE64
//
// by principal and then fingerprint, so an unchanged store gives the
// same bytes. The file is replaced whole, by a rename, so sshd never
// reads part of one (replaceFile).
//
// A daemon calls it once before it listens, and fails to start on its
// error, which names a fix. From then on the server calls it itself:
// after each control write that can change the keys, before the admin is
// answered, and on each reaper tick, which is also how a `starfixd
// control init` run beside the daemon reaches the file and how a failed
// write is tried again. A server with no Config.KeysFile writes nothing.
func (s *Server) WriteKeys() error { return s.writeKeys(context.Background()) }

// writeKeys is WriteKeys under ctx's span: a keys_file.write span of its
// own, which says whether the file was changed.
func (s *Server) writeKeys(ctx context.Context) error {
	path := s.cfg.KeysFile
	if path == "" {
		return nil
	}
	ctx, span := s.cfg.Telemetry.Start(ctx, telemetry.SpanKeysFile)
	defer span.End()
	log := s.cfg.Logger
	k := &s.keys
	k.mu.Lock()
	defer k.mu.Unlock()
	want, n, held := s.keyLines()
	at, written, err := syncFile(path, want)
	if err != nil {
		k.failed = true
		s.cfg.Telemetry.Count(telemetry.KeysFileWrites, telemetry.ResultFailed)
		span.Set(telemetry.KeyResult, telemetry.ResultFailed)
		span.Fail(telemetry.ResultFailed)
		return fmt.Errorf("write the keys file %s: %w", path, err)
	}
	span.Set(telemetry.KeyResult, telemetry.ResultOK)
	span.Set(telemetry.KeyChanged, strconv.FormatBool(written))
	if written {
		log.InfoContext(ctx, "keys file written", "event", logs.KeysFileWritten, "path", path, "keys", n)
		s.cfg.Telemetry.Count(telemetry.KeysFileWrites, telemetry.ResultOK)
	}
	s.cfg.Telemetry.Record(telemetry.KeysFileLastWrite, float64(at.Unix()))
	if written || len(held) != k.held {
		// Said when it changes, not on every tick.
		for _, h := range held {
			log.WarnContext(ctx, "a key of the control store is held back from the keys file: the authorized_keys file gives it to another principal, and sshd reads the keys file first",
				"event", logs.KeysFileHeldBack, "fingerprint", h.Fingerprint, "subject", h.Principal)
		}
	}
	k.keys, k.at, k.failed, k.held = n, at, false, len(held)
	return nil
}

// syncKeys is WriteKeys after the start: a failure is logged, and what
// it returns is the warning for the admin whose change the file does not
// show, or "" when the file is current. The control write has committed,
// so it is neither failed nor undone.
func (s *Server) syncKeys(ctx context.Context) string {
	err := s.writeKeys(ctx)
	if err == nil {
		return ""
	}
	s.cfg.Logger.ErrorContext(ctx, "the keys file is out of date; sshd reads the old one until a write succeeds", "event", logs.KeysFileWriteFailed, "err", err)
	return "the change is recorded, but starfixd could not write the keys file sshd reads, so sshd may still be reading the old one: " +
		"a key just added does not sign in yet, and a key just removed, or a disabled principal's, still passes sshd and is then refused by starfixd. " +
		"starfixd tries again every half minute; ask the server's operator to check its log, and see the keys file line of `sfx admin status`"
}

// keyLines renders the keys file, and returns how many keys it holds. A
// line is built only from what the store holds, each part checked again
// here: the principal is a principal name that is not reserved, the
// fingerprint is the stored key's own, and the key is one public key
// with no options, written back by the parser. A row that fails is left
// out and logged, without its text.
//
// A key that the hand-maintained file gives to another principal is
// held back, and returned: sshd reads this file first (decision 26), so
// its line would shadow the operator's, and sign that key's owner in as
// the store's principal. The store refuses to take such a key
// (Control.KeysElsewhere), so this is a line the operator added after
// the store had the key. s.keys.mu is held.
func (s *Server) keyLines() (lines []byte, n int, held []store.PrincipalKey) {
	var b bytes.Buffer
	b.WriteString(keysFileHeader)
	_, owner := s.handLocked()
	for _, k := range s.cfg.Control.AuthorizedKeys() {
		if o, ok := owner[k.Fingerprint]; ok && o != k.Principal {
			held = append(held, k)
			continue
		}
		pub, err := publicKey(k.Key)
		switch {
		case !PrincipalPattern.MatchString(k.Principal) || store.Reserved(k.Principal):
			err = errors.New("its principal is not a principal's name, or is reserved")
		case err == nil && ssh.FingerprintSHA256(pub) != k.Fingerprint:
			err = errors.New("its fingerprint is not the stored key's")
		}
		if err != nil {
			s.cfg.Logger.Error("a key of the control store is left out of the keys file", "event", logs.KeysFileLeftOut, "fingerprint", k.Fingerprint, "err", err)
			continue
		}
		fmt.Fprintf(&b, "restrict,command=\"%s stdio --principal %s --key %s\" %s\n",
			s.cfg.Bridge, k.Principal, k.Fingerprint, strings.TrimSpace(string(ssh.MarshalAuthorizedKey(pub))))
		n++
	}
	return b.Bytes(), n, held
}

// publicKey parses line as one public key, TYPE BASE64, with no options
// and no certificate. Its error never repeats the line.
func publicKey(line string) (ssh.PublicKey, error) {
	if strings.ContainsAny(line, "\r\n") {
		return nil, errors.New("not one line")
	}
	pub, _, options, rest, err := ssh.ParseAuthorizedKey([]byte(line))
	if err != nil || len(options) > 0 || len(rest) > 0 {
		return nil, errors.New("not a public key")
	}
	if _, cert := pub.(*ssh.Certificate); cert {
		return nil, errors.New("a certificate, not a public key")
	}
	return pub, nil
}

// syncFile makes the file at path hold want. It returns when the file
// took that content, and whether it was written: a file that held it
// already is left alone, and the time is then the file's own. Each error
// names its fix.
//
// It refuses a directory that group or others may write to, which
// sshd's StrictModes refuses too; a path that is a symbolic link or
// anything but a regular file; and a file that starfixd did not
// generate, so that a keys_file pointed at the operator's
// authorized_keys never replaces it.
func syncFile(path string, want []byte) (at time.Time, written bool, err error) {
	dir := filepath.Dir(path)
	switch di, err := os.Stat(dir); {
	case err != nil || !di.IsDir():
		return time.Time{}, false, fmt.Errorf("its directory %s is missing or is no directory; fix: create it as the user starfixd runs as (install -d -m 0700 %s), or set keys_file: to a file sshd reads", dir, dir)
	case runtime.GOOS != "windows" && di.Mode().Perm()&0o022 != 0:
		return time.Time{}, false, fmt.Errorf("its directory %s is mode %04o, writable by group or others, and sshd would not read keys from it; fix: chmod go-w %s", dir, di.Mode().Perm(), dir)
	}
	switch fi, err := os.Lstat(path); {
	case errors.Is(err, fs.ErrNotExist):
	case err != nil:
		return time.Time{}, false, fmt.Errorf("%w; fix: let the user starfixd runs as read %s", err, dir)
	case !fi.Mode().IsRegular():
		return time.Time{}, false, fmt.Errorf("it is %s, not a regular file, and starfixd writes through no link; fix: remove it, or set keys_file: to another path", kind(fi.Mode()))
	default:
		have, err := readUpTo(path, int64(len(want))+1)
		if err != nil {
			return time.Time{}, false, fmt.Errorf("%w; fix: make the file readable and writable by the user starfixd runs as, or remove it", err)
		}
		if bytes.Equal(have, want) {
			return fi.ModTime(), false, nil
		}
		if len(have) > 0 && !bytes.HasPrefix(have, []byte(keysFileHeader)) {
			return time.Time{}, false, errors.New("the file there was not generated by starfixd, and is left as it is; fix: set keys_file: to a file of its own, beside authorized_keys and never that file itself, or move the file away")
		}
	}
	if err := replaceFile(path, want); err != nil {
		return time.Time{}, false, fmt.Errorf("%w; fix: let the user starfixd runs as write to %s: under systemd with ProtectSystem=strict, add ReadWritePaths=%s to the unit (docs/server.md, Keys from the store)", err, dir, dir)
	}
	return time.Now(), true, nil
}

// kind names what a path is, for a refusal.
func kind(m fs.FileMode) string {
	switch {
	case m&fs.ModeSymlink != 0:
		return "a symbolic link"
	case m.IsDir():
		return "a directory"
	}
	return "a special file"
}

// replaceFile writes data to a new file beside path, mode 0600, and
// renames it over path, syncing the file before and the directory after:
// a reader sees the old file or the new, never part of one, and so does
// a machine that lost power.
func replaceFile(path string, data []byte) (err error) {
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-*") // mode 0600
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = f.Close()
			_ = os.Remove(f.Name())
		}
	}()
	if _, err = f.Write(data); err != nil {
		return err
	}
	if err = f.Sync(); err != nil {
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	if err = os.Rename(f.Name(), path); err != nil {
		return err
	}
	if runtime.GOOS == "windows" {
		return nil // a directory cannot be synced there, and no daemon runs there
	}
	d, err := os.Open(dir) //nolint:gosec // the operator's setting
	if err != nil {
		return err
	}
	return errors.Join(d.Sync(), d.Close())
}

// readUpTo reads at most n bytes of the regular file at path.
func readUpTo(path string, n int64) ([]byte, error) {
	f, err := os.Open(path) //nolint:gosec // the operator's setting
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	return io.ReadAll(io.LimitReader(f, n))
}

// keysStatus is the keys file as `sfx admin status` shows it, or nil for
// a server that writes none.
func (s *Server) keysStatus() *proto.KeysFile {
	if s.cfg.KeysFile == "" {
		return nil
	}
	k := &s.keys
	k.mu.Lock()
	defer k.mu.Unlock()
	out := &proto.KeysFile{Path: s.cfg.KeysFile, Keys: k.keys, Failed: k.failed, HeldBack: k.held}
	if !k.at.IsZero() {
		at := k.at.UTC()
		out.WrittenAt = &at
	}
	return out
}

// byHand returns the fingerprints of the keys in the authorized_keys
// file the operator maintains by hand (Config.AuthorizedKeys), which
// sshd reads after the keys file: a key in both is accepted there once
// it is removed from the store, by a line whose forced command names no
// fingerprint. The daemon runs as the account whose file it is,
// so it can read it. It never writes to it, and nothing read from it is
// logged or sent anywhere but as the answer "this key is in it".
//
// It is the operator's file, so it is read leniently: a line that is not
// a public key is skipped, and so is the whole file when it is missing,
// unreadable or no regular file. Only its first mebibyte is read. The
// answer is kept until the file's size or time changes.
func (s *Server) byHand() map[string]bool {
	k := &s.keys
	k.mu.Lock()
	defer k.mu.Unlock()
	hand, _ := s.handLocked()
	return hand
}

// handLocked is byHand with s.keys.mu held. It also returns, for each
// line whose forced command names a principal, that principal by the
// key's fingerprint.
func (s *Server) handLocked() (hand map[string]bool, owner map[string]string) {
	k := &s.keys
	path := s.cfg.AuthorizedKeys
	if path == "" {
		return nil, nil
	}
	fi, err := os.Stat(path)
	if err != nil || !fi.Mode().IsRegular() {
		k.hand, k.handOwner = nil, nil
		return nil, nil
	}
	if k.hand != nil && k.handSize == fi.Size() && k.handTime.Equal(fi.ModTime()) {
		return k.hand, k.handOwner
	}
	b, err := readUpTo(path, maxAuthorizedKeys)
	if err != nil {
		k.hand, k.handOwner = nil, nil
		return nil, nil
	}
	hand, owner = map[string]bool{}, map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	sc.Buffer(nil, maxAuthorizedKeys)
	for sc.Scan() {
		pub, _, options, _, err := ssh.ParseAuthorizedKey(sc.Bytes())
		if err != nil {
			continue
		}
		fp := ssh.FingerprintSHA256(pub)
		// sshd takes the first line that matches a key.
		if !hand[fp] {
			if p := forcedPrincipal(options); p != "" {
				owner[fp] = p
			}
		}
		hand[fp] = true
	}
	k.hand, k.handOwner, k.handSize, k.handTime = hand, owner, fi.Size(), fi.ModTime()
	return hand, owner
}

// forcedPrincipal returns the principal that the forced command among
// the options of an authorized_keys line names, `command="… stdio
// --principal NAME"` as the server guide writes it, or "" when the line
// forces no such command or names nothing a principal may be called.
func forcedPrincipal(options []string) string {
	for _, o := range options {
		cmd, ok := strings.CutPrefix(o, `command="`)
		if !ok {
			continue
		}
		f := strings.Fields(strings.TrimSuffix(cmd, `"`))
		if i := slices.Index(f, "--principal"); i >= 0 && i+1 < len(f) && PrincipalPattern.MatchString(f[i+1]) {
			return f[i+1]
		}
	}
	return ""
}

// handOwner returns the principal that the hand-maintained file's line
// for the key with a fingerprint names, and false when the file has no
// such line or the line names none. The control store asks it of every
// key it is about to add (store.Control.KeysElsewhere): sshd reads the
// keys file first (decision 26), so a key of that file added to the
// store under another name would sign its owner in as someone else.
func (s *Server) handOwner(fingerprint string) (string, bool) {
	k := &s.keys
	k.mu.Lock()
	defer k.mu.Unlock()
	_, owner := s.handLocked()
	p, ok := owner[fingerprint]
	return p, ok
}

// handWarning tells the admin who removed a key from the store that the
// hand-maintained file still lets it in. sshd reads the keys file
// first (decision 26), so while the store held the key its connections
// came in by the store's line and the removal closed them; with that
// line gone, sshd finds the hand-maintained one.
func handWarning(fingerprint string) string {
	return fmt.Sprintf("sshd will still accept key %s: the connections it had signed in were closed, but it is also a line of the server's authorized_keys file, "+
		"which starfixd never edits and sshd reads after starfixd's keys file. Its next connection comes in by that line, as the principal the line names, and names no key. "+
		"Ask the server's operator to delete the line (docs/server.md, Keys from the store); until then, disabling the principal that line names is what keeps the key out", fingerprint)
}

// accessActor is who the daemon's own writes are recorded as when it
// ends the claims of holders it finds without access (Sweep): the
// server, as the reaper's are, in a session of its own.
var accessActor = store.Actor{Principal: store.ReaperActor.Principal, Session: "access", Machine: "server"}

// Why a claim ended with its holder's access (decision 21), as the
// claim.release event and the holder's inbox item give it.
const (
	lostMembership = "membership removed"
	lostDisabled   = "principal disabled"
	lostArchived   = "project archived"
)

// lost says why principal has no access to project now, or "" when it
// has: the project is not active, the principal is disabled, or it is
// neither a member nor a server admin.
func (s *Server) lost(principal, project string) string {
	acc := s.cfg.Control.Access(principal, project)
	switch {
	case !acc.Active:
		return lostArchived
	case acc.Disabled:
		return lostDisabled
	case acc.Role == "":
		return lostMembership
	}
	return ""
}

// Sweep ends, in every open store, the claims held by principals who no
// longer have access to that store's project (decision 21), as the
// reaper loop does on each tick and a store does as it opens. An admin's
// change ends the claims in the stores open when it commits, under the
// admin's name (release); a store closed then has no one to end them,
// so they end here when it next opens, before its first request, under
// the server's name. It is also what ends them when the daemon stopped
// between the change and the release. A server of one project has
// nothing to sweep.
func (s *Server) Sweep(ctx context.Context) {
	if s.stores == nil {
		return
	}
	ctx, span := s.cfg.Telemetry.Start(ctx, telemetry.SpanSweep)
	defer span.End()
	s.stores.each(func(pr *served) { s.sweepStore(ctx, pr) })
}

// sweep is Sweep for one project's store, as it opens or is retired: an
// access.sweep span that names the project.
func (s *Server) sweep(ctx context.Context, pr *served) {
	if s.cfg.Control == nil {
		return
	}
	ctx, span := s.cfg.Telemetry.Start(ctx, telemetry.SpanSweep)
	defer span.End()
	span.Set(telemetry.KeyProject, pr.id)
	s.sweepStore(ctx, pr)
}

// sweepStore ends the claims in pr whose holders lost their access.
func (s *Server) sweepStore(ctx context.Context, pr *served) {
	s.endClaims(ctx, pr, accessActor, func(holder string) string { return s.lost(holder, pr.id) })
}

// release ends, as by, the claims principal holds in project's store
// for reason, and returns how many: in every open store when project is
// empty, and of every holder when principal is. It looks only at stores
// that are open; Sweep ends the rest when their stores open.
//
// The caller has committed the change that ended the access. A store
// that fails here is logged, and swept on the reaper's next tick.
func (s *Server) release(ctx context.Context, by store.Actor, project, principal, reason string) int {
	n := 0
	s.stores.eachOf(project, func(pr *served) {
		n += s.endClaims(ctx, pr, by, func(holder string) string {
			if principal == "" || holder == principal {
				return reason
			}
			return ""
		})
	})
	return n
}

// endClaims ends the claims in pr that why gives a reason for, as by,
// logs each, and returns how many.
func (s *Server) endClaims(ctx context.Context, pr *served, by store.Actor, why func(holder string) string) int {
	ectx, cancel := context.WithTimeout(ctx, pr.timeout)
	defer cancel()
	cs, err := pr.store.EndClaims(ectx, by, why)
	if err != nil {
		if ctx.Err() == nil {
			pr.log.ErrorContext(ctx, "end the claims of holders without access", "event", logs.SweepFailed, "err", err)
		}
		return 0
	}
	for _, c := range cs {
		pr.log.InfoContext(ctx, "claim released: access ended", "event", logs.ClaimReleased, "issue", c.Issue, "principal", c.Holder.Principal,
			"session", c.Holder.Session, "epoch", c.Epoch, "by", by.Principal, "reason", why(c.Holder.Principal))
	}
	return len(cs)
}
