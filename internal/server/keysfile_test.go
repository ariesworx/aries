// keysLine is the line the keys file holds for owner's test key.
func keysLine(t *testing.T, owner string) string {
	t.Helper()
	typ, blob, fp, _ := testKey(t, owner)
	return fmt.Sprintf("restrict,command=\"/usr/local/bin/starfixd stdio --principal %s --key %s\" %s %s\n", owner, fp, typ, blob)
}

// keysFileOf returns the keys file's lines after its first, which must
// say that starfixd generates the file.
func (m *multi) keysFileOf(t *testing.T) string {
	t.Helper()
	b, err := os.ReadFile(m.keysFile)
	if err != nil {
		t.Fatalf("read the keys file: %v", err)
	}
	header, lines, ok := strings.Cut(string(b), "\n")
	if !ok || !strings.HasPrefix(header, "# Generated by starfixd") || !strings.Contains(header, "changes are overwritten") {
		t.Fatalf("the keys file starts with %q; want a comment saying starfixd generates it and overwrites edits", header)
	}
	return lines
}

// sshd reads the keys file as sshd does, and returns the principal the
// line for the key with the given fingerprint lets in, or "" when the
// file has no line for it. It fails the test for a line that does more
// than force the bridge for that principal and that key.
func (m *multi) sshd(t *testing.T, fingerprint string) string {
	t.Helper()
	for line := range strings.Lines(m.keysFileOf(t)) {
		pub, comment, options, rest, err := ssh.ParseAuthorizedKey([]byte(line))
		if err != nil || comment != "" || len(rest) != 0 || len(options) != 2 || options[0] != "restrict" {
			t.Fatalf("the keys file holds a line sshd would not read as one restricted key and nothing else: %q (%v)", line, err)
		}
		fp := ssh.FingerprintSHA256(pub)
		cmd, ok := strings.CutPrefix(options[1], `command="`+DefaultBridge+` stdio --principal `)
		principal, key, named := strings.Cut(strings.TrimSuffix(cmd, `"`), " --key ")
		if !ok || !named || key != fp || !PrincipalPattern.MatchString(principal) {
			t.Fatalf("the keys file's line for %s forces %q; want the bridge, a principal and that key's fingerprint", fp, options[1])
		}
		if fp == fingerprint {
			return principal
		}
	}
	return ""
}

// TestKeysFile follows the keys file through every change that can alter
// what sshd should accept: it holds exactly the keys of the active
// principals, one line each, by the time the admin is answered.
func TestKeysFile(t *testing.T) {
	t.Parallel()
	m := adminWorld(t, Limits{}) // carol has a key
	d := mustDialTo(t, m.Server, dana, projA)
	check := func(when string, owners ...string) {
		t.Helper()
		var want strings.Builder
		for _, o := range owners {
			want.WriteString(keysLine(t, o))
		}
		if got := m.keysFileOf(t); got != want.String() {
			t.Errorf("%s, the keys file holds\n%swant\n%s", when, got, want.String())
		}
	}
	check("at the start", "carol")
	if fi, err := os.Lstat(m.keysFile); err != nil || !fi.Mode().IsRegular() || (runtime.GOOS != "windows" && fi.Mode().Perm() != 0o600) {
		t.Errorf("the keys file is %v (%v), want a regular file of mode 0600", fi.Mode(), err)
	}

	mustAsk[proto.KeyResult](d, proto.OpKeyAdd, proto.KeyAddArgs{Name: "bob", Key: keyLine(t, "bob")})
	check("after key.add", "bob", "carol")
	mustAsk[proto.PrincipalAddResult](d, proto.OpPrincipalAdd, proto.PrincipalAddArgs{Name: "hal", Keys: []string{keyLine(t, "hal")}})
	check("after principal.add with a key", "bob", "carol", "hal")
	// A principal's keys are by fingerprint, whatever order they came in.
	mustAsk[proto.KeyResult](d, proto.OpKeyAdd, proto.KeyAddArgs{Name: "bob", Key: keyLine(t, "bob 2")})
	lines := m.keysFileOf(t)
	if a, b := strings.Index(lines, fingerprintOf(t, "bob")), strings.Index(lines, fingerprintOf(t, "bob 2")); a < 0 || b < 0 ||
		(a < b) != (fingerprintOf(t, "bob") < fingerprintOf(t, "bob 2")) || strings.Index(lines, "--principal carol") < max(a, b) {
		t.Errorf("after a second key for bob, the keys file is not by principal and then fingerprint:\n%s", lines)
	}
	mustAsk[proto.KeyResult](d, proto.OpKeyRemove, proto.KeyRemoveArgs{Fingerprint: fingerprintOf(t, "bob 2")})
	check("after key.remove", "bob", "carol", "hal")
	mustAsk[proto.PrincipalResult](d, proto.OpPrincipalDisable, proto.PrincipalArgs{Name: "carol"})
	check("after principal.disable", "bob", "hal")
	mustAsk[proto.PrincipalResult](d, proto.OpPrincipalEnable, proto.PrincipalArgs{Name: "carol"})
	check("after principal.enable", "bob", "carol", "hal")
	for _, owner := range []string{"bob", "carol", "hal"} {
		if got := m.sshd(t, fingerprintOf(t, owner)); got != owner {
			t.Errorf("sshd reads the line of %s's key as letting in %q", owner, got)
		}
	}
	if log := m.log.String(); strings.Contains(log, "level=ERROR") {
		t.Errorf("the log has an error:\n%s", log)
	}

	// Nothing changed, so nothing is written: the same file is there.
	before, err := os.Stat(m.keysFile)
	if err != nil {
		t.Fatal(err)
	}
	content, _ := os.ReadFile(m.keysFile)
	writes := strings.Count(m.log.String(), `msg="keys file written"`)
	m.refresh(t.Context())
	mustAsk[proto.MemberSetResult](d, proto.OpMemberSet, proto.MemberSetArgs{Name: "hal", Role: "admin"})
	mustAsk[proto.KeyResult](d, proto.OpKeyAdd, proto.KeyAddArgs{Name: "bob", Key: keyLine(t, "bob")}) // a key bob has
	if err := m.WriteKeys(); err != nil {
		t.Fatal(err)
	}
	after, err := os.Stat(m.keysFile)
	if err != nil || !os.SameFile(before, after) || !after.ModTime().Equal(before.ModTime()) {
		t.Errorf("the keys file was replaced with nothing to change (%v): %v, then %v", err, before.ModTime(), after.ModTime())
	}
	if n := strings.Count(m.log.String(), `msg="keys file written"`); n != writes {
		t.Errorf("%d writes of the keys file were logged with nothing to change", n-writes)
	}
	// An edit is overwritten at the next tick, as the first line says.
	if err := os.WriteFile(m.keysFile, append(content, "ssh-ed25519 AAAA not-a-key\n"...), 0o600); err != nil { //nolint:gosec // the test's own file
		t.Fatal(err)
	}
	m.refresh(t.Context())
	check("after an edit and a tick", "bob", "carol", "hal")
	// No temporary file is left beside it.
	entries, err := os.ReadDir(filepath.Dir(m.keysFile))
	if err != nil || len(entries) != 1 {
		t.Errorf("the keys file's directory holds %v (%v), want the keys file alone", entries, err)
	}
}

// TestKeysFileFollowsTheOperator checks that what `starfixd control
// init` writes beside the daemon reaches the keys file at the next tick.
func TestKeysFileFollowsTheOperator(t *testing.T) {
	t.Parallel()
	m := adminWorld(t, Limits{})
	op, err := store.OpenControl(t.Context(), m.dsn, store.ControlOptions{CommitInterval: -1, Operator: true})
	if err != nil {
		t.Fatal(err)
	}
	operator := store.Actor{Principal: store.OperatorPrincipal, Session: "init", Machine: "server"}
	_, err = op.AddKey(t.Context(), operator, "bob", keyLine(t, "bob"))
	if err = errors.Join(err, op.Close()); err != nil {
		t.Fatal(err)
	}
	if got := m.sshd(t, fingerprintOf(t, "bob")); got != "" {
		t.Fatalf("the keys file gives bob's key to %q before the daemon has read the control database again", got)
	}
	m.refresh(t.Context())
	if got := m.sshd(t, fingerprintOf(t, "bob")); got != "bob" {
		t.Errorf("after a tick the keys file gives the key the operator added to %q, want bob", got)
	}
}

// TestKeysFileRefusals checks what the server will not write to, and
// that each refusal names its fix and leaves what is there alone.
func TestKeysFileRefusals(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("modes and links as sshd reads them are not Windows's")
	}
	const theirs = "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIPCmbfhy2nWjY0kb3ghKVOyVhSBBnOKPi9y4uhT9iJtw someone@example.com\n"
	tests := []struct {
		name  string
		setup func(t *testing.T, dir, path string)
		err   string
		kept  string // what path must still hold, if anything
	}{
		{"a symbolic link", func(t *testing.T, dir, path string) {
			if err := os.WriteFile(filepath.Join(dir, "elsewhere"), []byte(theirs), 0o600); err != nil {
				t.Fatal(err)
			}
			if err := os.Symlink(filepath.Join(dir, "elsewhere"), path); err != nil {
				t.Fatal(err)
			}
		}, "it is a symbolic link, not a regular file", theirs},
		{"a directory", func(t *testing.T, _, path string) {
			if err := os.Mkdir(path, 0o700); err != nil {
				t.Fatal(err)
			}
		}, "it is a directory, not a regular file", ""},
		{"a directory others may write to", func(t *testing.T, dir, _ string) {
			if err := os.Chmod(dir, 0o777); err != nil { //nolint:gosec // the mode under test
				t.Fatal(err)
			}
		}, "writable by group or others", ""},
		{"a directory the group may write to", func(t *testing.T, dir, _ string) {
			if err := os.Chmod(dir, 0o770); err != nil { //nolint:gosec // the mode under test
				t.Fatal(err)
			}
		}, "writable by group or others", ""},
		{"no directory", func(t *testing.T, dir, _ string) {
			if err := os.Remove(dir); err != nil {
				t.Fatal(err)
			}
		}, "is missing or is no directory", ""},
		{"a file starfixd did not generate", func(t *testing.T, _, path string) {
			if err := os.WriteFile(path, []byte(theirs), 0o600); err != nil {
				t.Fatal(err)
			}
		}, "was not generated by starfixd, and is left as it is", theirs},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			dir := filepath.Join(t.TempDir(), ".ssh")
			if err := os.Mkdir(dir, 0o700); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(dir, "starfix_keys")
			tc.setup(t, dir, path)
			_, written, err := syncFile(path, []byte(keysFileHeader+"a line\n"))
			if err == nil || written || !strings.Contains(err.Error(), tc.err) || !strings.Contains(err.Error(), "; fix: ") {
				t.Fatalf("syncFile = written %v, %v; want an error containing %q and a fix", written, err, tc.err)
			}
			if tc.kept != "" {
				if b, err := os.ReadFile(path); err != nil || string(b) != tc.kept { //nolint:gosec // the test's own file
					t.Errorf("after the refusal the path holds %q (%v), want it untouched", b, err)
				}
			}
		})
	}

	t.Run("an empty file is taken over", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "starfix_keys")
		if err := os.WriteFile(path, nil, 0o644); err != nil { //nolint:gosec // widened on purpose
			t.Fatal(err)
		}
		if _, written, err := syncFile(path, []byte(keysFileHeader)); err != nil || !written {
			t.Fatalf("syncFile over an empty file = written %v, %v", written, err)
		}
		if fi, err := os.Stat(path); err != nil || fi.Mode().Perm() != 0o600 {
			t.Errorf("the file written is mode %v (%v), want 0600", fi.Mode().Perm(), err)
		}
	})

	// The settings the server will not start with.
	ctl := adminWorld(t, Limits{}).ctl
	open := func(context.Context, store.Project) (*store.Store, error) { return nil, errors.New("not opened") }
	for _, tc := range []struct {
		name string
		cfg  Config
		err  string
	}{
		{"a relative keys file", Config{Control: ctl, Open: open, KeysFile: ".ssh/starfix_keys"}, "an absolute path"},
		{"a keys file that is the authorized_keys file", Config{Control: ctl, Open: open, KeysFile: "/srv/keys", AuthorizedKeys: "/srv/x/../keys"},
			"is the authorized_keys file, which starfixd never writes"},
		{"a relative authorized_keys file", Config{Control: ctl, Open: open, AuthorizedKeys: "authorized_keys"}, "an absolute path"},
		{"a bridge that needs quoting", Config{Control: ctl, Open: open, Bridge: `/usr/local/bin/starfixd" ssh-ed25519 AAAA`}, "must be absolute, of letters, digits and ._+-"},
		{"a keys file on a server of one project", Config{Store: newServer(t).cfg.Store, Project: project, KeysFile: "/srv/keys"}, "needs a control store"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := New(tc.cfg); err == nil || !strings.Contains(err.Error(), tc.err) {
				t.Errorf("New = %v, want an error containing %q", err, tc.err)
			}
		})
	}
}

// TestKeysFileWriteFails is a write that fails after the start. The
// control write has committed and stays: the admin is answered, with a
// warning; the log and `status` say the file is out of date; the daemon
// refuses the removed key at the handshake, whatever the stale file lets
// past sshd; and the next tick that can write puts the file right.
func TestKeysFileWriteFails(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("needs a directory this user cannot write to")
	}
	m := adminWorld(t, Limits{})
	carols, dir := fingerprintOf(t, "carol"), filepath.Dir(m.keysFile)
	d := mustDialTo(t, m.Server, dana, projA)
	status := func() *proto.KeysFile {
		t.Helper()
		res := mustAsk[proto.StatusResult](d, proto.OpStatus, proto.StatusArgs{})
		if res.Server == nil || res.Server.KeysFile == nil {
			t.Fatalf("status for a server admin has no keys file: %+v", res.Server)
		}
		return res.Server.KeysFile
	}
	if k := status(); k.Path != m.keysFile || k.Keys != 1 || k.Failed || k.WrittenAt == nil || time.Since(*k.WrittenAt) > time.Minute {
		t.Errorf("status of the keys file = %+v; want %s with 1 key, written just now", k, m.keysFile)
	}

	if err := os.Chmod(dir, 0o500); err != nil { //nolint:gosec // a directory the server cannot write to
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(dir, 0o700) }) //nolint:gosec // back to what it was
	const warning = "the change is recorded, but starfixd could not write the keys file sshd reads, so sshd may still be reading the old one: "
	rm := mustAsk[proto.KeyResult](d, proto.OpKeyRemove, proto.KeyRemoveArgs{Fingerprint: carols})
	if rm.ID != carols || !strings.HasPrefix(rm.Warning, warning) || !strings.Contains(rm.Warning, "`sfx admin status`") {
		t.Errorf("key.remove with the keys file unwritable = %+v; want the key removed, and a warning that sshd may read the old file", rm)
	}
	if _, _, ok := m.ctl.AuthorizedKey(carols); ok {
		t.Error("the key is still in the store: a failed write of the file must not undo the removal")
	}
	if got := m.sshd(t, carols); got != "carol" {
		t.Fatalf("the stale keys file gives carol's key to %q; the test needs it still there", got)
	}
	// The store decides: sshd would let the key in, and the daemon does not.
	if w, _, closed := dialKey(t, m.Server, carol, projA, carols); closed || w.Err == nil || w.Err.Code != proto.CodeAuth || w.Err.Fix == "" {
		t.Errorf("a handshake by a removed key that a stale keys file still holds = %+v, closed %v; want an auth refusal with a fix", w, closed)
	}
	if log := m.log.String(); !strings.Contains(log, `level=ERROR msg="the keys file is out of date; sshd reads the old one until a write succeeds"`) ||
		!strings.Contains(log, "ReadWritePaths="+dir) {
		t.Errorf("the log lacks the failed write, or its fix:\n%s", log)
	}
	if k := status(); !k.Failed || k.Keys != 1 || k.WrittenAt == nil {
		t.Errorf("status of the keys file after a failed write = %+v; want it failed, still with the 1 key last written", k)
	}
	// Every result that can change the file carries the warning.
	for _, tc := range []struct {
		name string
		ask  func() string
	}{
		{"key.add", func() string {
			return mustAsk[proto.KeyResult](d, proto.OpKeyAdd, proto.KeyAddArgs{Name: "bob", Key: keyLine(t, "bob")}).Warning
		}},
		{"principal.add with a key", func() string {
			return mustAsk[proto.PrincipalAddResult](d, proto.OpPrincipalAdd, proto.PrincipalAddArgs{Name: "hal", Keys: []string{keyLine(t, "hal")}}).Warning
		}},
		{"principal.disable", func() string {
			return mustAsk[proto.PrincipalResult](d, proto.OpPrincipalDisable, proto.PrincipalArgs{Name: "bob"}).Warning
		}},
		{"principal.enable", func() string {
			return mustAsk[proto.PrincipalResult](d, proto.OpPrincipalEnable, proto.PrincipalArgs{Name: "bob"}).Warning
		}},
	} {
		if got := tc.ask(); !strings.HasPrefix(got, warning) {
			t.Errorf("%s with the keys file unwritable: warning %q, want one that sshd may read the old file", tc.name, got)
		}
	}
	// A principal added with no key changes nothing sshd reads.
	if got := mustAsk[proto.PrincipalAddResult](d, proto.OpPrincipalAdd, proto.PrincipalAddArgs{Name: "ivan"}).Warning; got != "" {
		t.Errorf("principal.add with no key, with the keys file unwritable: warning %q, want none", got)
	}
	// A tick that still cannot write changes nothing; one that can, does.
	m.refresh(t.Context())
	if k := status(); !k.Failed {
		t.Errorf("status after a tick that could not write = %+v, want it still failed", k)
	}
	if err := os.Chmod(dir, 0o700); err != nil { //nolint:gosec // back to what it was
		t.Fatal(err)
	}
	m.refresh(t.Context())
	if k := status(); k.Failed || k.Keys != 2 {
		t.Errorf("status after a tick that could write = %+v; want it current, with the keys of bob and hal", k)
	}
	if got := m.keysFileOf(t); got != keysLine(t, "bob")+keysLine(t, "hal") {
		t.Errorf("after the tick the keys file holds\n%swant the keys of bob and hal", got)
	}
}

// TestStaleKeysFrame is a root-owned copy of an unreleased starfixd,
// still some sshd's AuthorizedKeysCommand while its server is upgraded:
// its question is closed at once, unanswered, and logged below info.
func TestStaleKeysFrame(t *testing.T) {
	t.Parallel()
	m := adminWorld(t, Limits{})
	srv, cli := net.Pipe()
	done := make(chan struct{})
	go func() {
		defer close(done)
		defer func() { _ = srv.Close() }()
		m.handle(t.Context(), srv)
	}()
	defer func() { _ = cli.Close(); <-done }()
	if _, err := cli.Write([]byte(`{"t":"keys","k":"` + fingerprintOf(t, "carol") + `"}` + "\n")); err != nil {
		t.Fatal(err)
	}
	// Well inside the three seconds the old command waited.
	_ = cli.SetReadDeadline(time.Now().Add(2 * time.Second))
	if f, err := proto.NewDecoder(cli).Decode(); err == nil || errors.Is(err, os.ErrDeadlineExceeded) {
		t.Errorf("a keys first frame was answered with %+v (%v); want the connection closed at once, unanswered", f, err)
	}
	<-done
	if m.slots.total != 0 || m.OpenStores() != 0 {
		t.Errorf("the keys frame holds %d connection slots and %d open stores, want none", m.slots.total, m.OpenStores())
	}
	for line := range strings.Lines(m.log.String()) {
		if strings.Contains(line, "key lookup") && !strings.Contains(line, "level=DEBUG") {
			t.Errorf("the stale lookup is logged above debug: %s", line)
		}
	}
	if log := m.log.String(); strings.Contains(log, "handshake failed") || strings.Contains(log, fingerprintOf(t, "carol")) {
		t.Errorf("the stale lookup is logged as a failed handshake, or by its key:\n%s", log)
	}
}

