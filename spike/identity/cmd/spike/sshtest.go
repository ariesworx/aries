// A case is one key and its line in the keys file, with what sshd is
// expected to do with it in the server's zone.
type sshCase struct {
	Name   string `json:"name"`
	Expiry string `json:"expiry"` // the expiry-time value as written
	Accept bool   `json:"accept"`
	Why    string `json:"why"`
}

// cmdSSHKeys writes one key per case and an aries_keys file whose lines
// carry expiry-time in the forms that matter: UTC marked Z, UTC digits
// with no Z, and the server's local digits with no Z, each a few
// minutes ahead and one minute behind. -zone is the zone the container's
// sshd runs in, so that the expectation can be worked out here.
func cmdSSHKeys(_ context.Context, args []string) error {
	fs := flag.NewFlagSet("sshkeys", flag.ExitOnError)
	dir := fs.String("dir", "", "directory for the keys, aries_keys and expect.json")
	zone := fs.String("zone", "UTC", "the IANA zone sshd's machine is set to")
	extra := fs.String("extra", "", "a file of lines from `spike login` to add, with their keys beside them")
	_ = fs.Parse(args)
	if *dir == "" {
		return errors.New("-dir is required")
	}
	loc, err := time.LoadLocation(*zone)
	if err != nil {
		return err
	}
	now := time.Now()
	_, off := now.In(loc).Zone()
	offset := time.Duration(off) * time.Second

	// sshd, by its manual, reads digits with no Z in the system's zone.
	// So digits d mean the instant d-as-UTC minus the zone's offset.
	type spec struct {
		name  string
		at    time.Time
		local bool // digits in the zone, else UTC digits
		z     bool
	}
	specs := []spec{
		{"utc-z-ahead", now.Add(3 * time.Minute), false, true},
		{"utc-z-behind", now.Add(-time.Minute), false, true},
		{"utc-digits-ahead", now.Add(3 * time.Minute), false, false},
		{"utc-digits-behind", now.Add(-time.Minute), false, false},
		{"local-digits-ahead", now.Add(3 * time.Minute), true, false},
		{"local-digits-behind", now.Add(-time.Minute), true, false},
		{"hold", now.Add(60 * time.Second), false, true},
	}
	var lines strings.Builder
	lines.WriteString("# Generated by the spike, in the form ariesd writes.\n")
	var cases []sshCase
	for _, s := range specs {
		var digits string
		instant := s.at
		switch {
		case s.local:
			digits = s.at.In(loc).Format("20060102150405")
		default:
			digits = s.at.UTC().Format("20060102150405")
			if !s.z {
				instant = s.at.Add(-offset)
			}
		}
		val := digits
		if s.z {
			val += "Z"
		}
		pub, err := writeKey(filepath.Join(*dir, "k-"+s.name))
		if err != nil {
			return err
		}
		fmt.Fprintf(&lines, "restrict,expiry-time=%q,command=\"/usr/local/bin/aries-probe %s\" %s\n", val, s.name, trimNL(ssh.MarshalAuthorizedKey(pub)))
		accept := instant.After(now.Add(20 * time.Second)) // margin for the run
		why := fmt.Sprintf("means %s if read as the zone says", instant.UTC().Format(time.RFC3339))
		if s.z {
			why = fmt.Sprintf("means %s, marked UTC", instant.UTC().Format(time.RFC3339))
		}
		cases = append(cases, sshCase{Name: s.name, Expiry: val, Accept: accept, Why: why})
	}
	if *extra != "" {
		b, err := os.ReadFile(*extra)
		if err != nil {
			return err
		}
		for l := range strings.Lines(string(b)) {
			if strings.TrimSpace(l) == "" {
				continue
			}
			lines.WriteString(l)
		}
		cases = append(cases, sshCase{Name: "login", Accept: true, Why: "the line `spike login -mode loopback` returned"})
	}
	if err := os.WriteFile(filepath.Join(*dir, "aries_keys"), []byte(lines.String()), 0o600); err != nil {
		return err
	}
	b, _ := json.MarshalIndent(cases, "", "  ")
	fmt.Printf("sshkeys: zone %s (UTC%s), %d lines written at %s\n", *zone, fmtOffset(offset), len(cases), now.UTC().Format(time.RFC3339))
	return os.WriteFile(filepath.Join(*dir, "expect.json"), b, 0o600)
}

func fmtOffset(d time.Duration) string {
	if d == 0 {
		return ""
	}
	sign := "+"
	if d < 0 {
		sign, d = "-", -d
	}
	return fmt.Sprintf("%s%d", sign, int(d.Hours()))
}

func writeKey(path string) (ssh.PublicKey, error) {
	pubRaw, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return nil, err
	}
	block, err := ssh.MarshalPrivateKey(priv, "spike")
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(path, pem.EncodeToMemory(block), 0o600); err != nil {
		return nil, err
	}
	return ssh.NewPublicKey(pubRaw)
}

func loadKey(path string) (ssh.Signer, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return ssh.ParsePrivateKey(b)
}

// dial connects as aries with one key, which is the only one offered.
// The host key is not checked: the server is a container on loopback that
// the spike started.
func dial(addr string, key ssh.Signer) (*ssh.Client, error) {
	return ssh.Dial("tcp", addr, &ssh.ClientConfig{
		User:            "aries",
		Auth:            []ssh.AuthMethod{ssh.PublicKeys(key)},
		HostKeyCallback: ssh.InsecureIgnoreHostKey(), //nolint:gosec // a container the spike started, on loopback
		Timeout:         10 * time.Second,
	})
}

// run connects with key and returns the forced command's first line. An
// error means sshd refused the key; what the command then does is not
// the question.
func run(addr string, key ssh.Signer) (string, error) {
	c, err := dial(addr, key)
	if err != nil {
		return "", err
	}
	defer c.Close()
	s, err := c.NewSession()
	if err != nil {
		return "(no session)", nil
	}
	defer s.Close()
	out, _ := s.Output("whatever the client asks")
	return strings.TrimSpace(strings.SplitN(string(out), "\n", 2)[0]), nil
}

// cmdProbe connects with each case's key and compares with expect.json.
func cmdProbe(_ context.Context, args []string) error {
	fs := flag.NewFlagSet("probe", flag.ExitOnError)
	dir := fs.String("dir", "", "the directory sshkeys wrote")
	addr := fs.String("addr", "127.0.0.1:12222", "sshd's address")
	login := fs.String("login-key", "", "the key `spike login` made, for the case named login")
	_ = fs.Parse(args)
	b, err := os.ReadFile(filepath.Join(*dir, "expect.json"))
	if err != nil {
		return err
	}
	var cases []sshCase
	if err := json.Unmarshal(b, &cases); err != nil {
		return err
	}
	bad := 0
	for _, c := range cases {
		if c.Name == "hold" {
			continue
		}
		path := filepath.Join(*dir, "k-"+c.Name)
		if c.Name == "login" {
			path = *login
		}
		key, err := loadKey(path)
		if err != nil {
			return err
		}
		out, err := run(*addr, key)
		got := err == nil
		verdict := "as expected"
		if got != c.Accept {
			verdict = "NOT AS EXPECTED"
			bad++
		}
		what := "refused"
		if got {
			what = "admitted: " + out
		}
		fmt.Printf("probe: %-20s expiry-time=%-16s %s; %s (%s)\n", c.Name, c.Expiry, what, verdict, c.Why)
	}
	if bad > 0 {
		return fmt.Errorf("%d cases not as expected", bad)
	}
	return nil
}

// cmdHold opens a connection with the hold case's key, whose line
// expires a minute after sshkeys wrote it, and keeps reading the forced
// command's output past that time; then tries a second connection.
func cmdHold(_ context.Context, args []string) error {
	fs := flag.NewFlagSet("hold", flag.ExitOnError)
	dir := fs.String("dir", "", "the directory sshkeys wrote")
	addr := fs.String("addr", "127.0.0.1:12222", "sshd's address")
	_ = fs.Parse(args)
	b, err := os.ReadFile(filepath.Join(*dir, "expect.json"))
	if err != nil {
		return err
	}
	var cases []sshCase
	if err := json.Unmarshal(b, &cases); err != nil {
		return err
	}
	i := slices.IndexFunc(cases, func(c sshCase) bool { return c.Name == "hold" })
	if i < 0 {
		return errors.New("no hold case")
	}
	exp, err := time.Parse("20060102150405Z", cases[i].Expiry)
	if err != nil {
		return err
	}
	key, err := loadKey(filepath.Join(*dir, "k-hold"))
	if err != nil {
		return err
	}
	c, err := dial(*addr, key)
	if err != nil {
		return fmt.Errorf("first connection, before expiry: %w", err)
	}
	defer c.Close()
	s, err := c.NewSession()
	if err != nil {
		return err
	}
	out, _ := s.StdoutPipe()
	if err := s.Start("x"); err != nil {
		return err
	}
	fmt.Printf("hold: connected %s before the line's expiry\n", time.Until(exp).Round(time.Second))
	sc := bufio.NewScanner(out)
	var last time.Time
	n := 0
	for sc.Scan() {
		n++
		last = time.Now()
		if last.After(exp.Add(15 * time.Second)) {
			break
		}
	}
	if !last.After(exp) {
		return fmt.Errorf("the connection ended %s before expiry", exp.Sub(last).Round(time.Second))
	}
	fmt.Printf("hold: still receiving %s after the line's expiry (%d lines): sshd does not end a connection when its key expires\n",
		last.Sub(exp).Round(time.Second), n)
	if _, err := run(*addr, key); err != nil {
		var ne net.Error
		fmt.Printf("hold: a new connection with the same key after expiry: refused (%v, network error %v)\n", firstLine(err), errors.As(err, &ne))
	} else {
		return errors.New("a new connection after expiry was admitted")
	}
	return nil
}

func firstLine(err error) string { return strings.SplitN(err.Error(), "\n", 2)[0] }
